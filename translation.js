// Function to change the language and update the text on the page
export function changeLanguage(lang) {
    if (!translations[lang]) return;

    // Save preference to localStorage so it remembers the user's choice
    localStorage.setItem('preferredLanguage', lang);
    document.documentElement.lang = lang;

    // Find all elements that have the data-translate attribute
    const elementsToTranslate = document.querySelectorAll('[data-translate]');
    
    elementsToTranslate.forEach(element => {
        const key = element.getAttribute('data-translate');
        if (translations[lang][key]) {
            if (element.tagName === 'INPUT' && element.hasAttribute('placeholder')) {
                element.setAttribute('placeholder', translations[lang][key]);
            } else {
                element.textContent = translations[lang][key];
            }
        }
    });
}

// Function to initialize the page with the saved language
export function initializeWithDetection() {
    // Get saved language or default to English
    const savedLang = localStorage.getItem('preferredLanguage') || 'en';
    
    // Apply the language globally to the page
    changeLanguage(savedLang);

    // Update the button active states on load (if the buttons exist on the page)
    const buttons = document.querySelectorAll('.language-buttons button');
    buttons.forEach(btn => {
        btn.classList.remove('active');
        if (btn.getAttribute('data-lang') === savedLang) {
            btn.classList.add('active');
        }
    });
}